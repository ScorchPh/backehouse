<?php
// Create Bakery Product Endpoint
// 
// Purpose:
// Allows admin or staff users to add new items into the bakery inventory catalog.
// Validates inputs, executes a secure PDO prepared insert, and returns the newly created item with its MySQL ID.

require_once __DIR__ . '/../../config/db.php';

// Only allow POST requests for creating resources
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    sendResponse(['success' => false, 'message' => 'Method not allowed. Please use POST.'], 405);
}

// Parse JSON payload sent from frontend modal
$data = getRequestBody();

// Clean and sanitize incoming fields
$name           = trim($data['name'] ?? '');
$description    = trim($data['description'] ?? '');
$category       = trim($data['category'] ?? 'Cake');
$price          = (float)($data['price'] ?? 0.0);
$image          = trim($data['image'] ?? 'https://images.unsplash.com/photo-1578985545062-69928b1d9587?w=500');
$stock          = (int)($data['stock'] ?? 20);
$status         = trim($data['status'] ?? 'Available');
$expirationDate = !empty($data['expiration_date']) ? trim($data['expiration_date']) : null;
$bestseller     = !empty($data['bestseller']) ? 1 : 0;

// Mandatory field validation: name is required and price must be greater than zero
if (empty($name) || $price <= 0) {
    sendResponse(['success' => false, 'message' => 'Product name and a positive price are required.'], 400);
}

// Connect to database
$pdo = getDBConnection();
if (!$pdo) {
    sendResponse(['success' => false, 'message' => 'Database connection failed'], 500);
}

// Ensure expiration_date column exists
try {
    $colStmt = $pdo->query("SHOW COLUMNS FROM `products` LIKE 'expiration_date'");
    if ($colStmt && $colStmt->rowCount() === 0) {
        $pdo->exec("ALTER TABLE `products` ADD COLUMN `expiration_date` DATE NULL AFTER `stock`");
    }
} catch (Throwable $e) {}

try {
    // Prepared statement with parameterized query protects against SQL injection
    $stmt = $pdo->prepare("
        INSERT INTO products (name, description, category, price, image, stock, status, expiration_date, bestseller)
        VALUES (:name, :description, :category, :price, :image, :stock, :status, :expiration_date, :bestseller)
    ");

    $stmt->execute([
        'name'            => $name,
        'description'     => $description,
        'category'        => $category,
        'price'           => $price,
        'image'           => $image,
        'stock'           => $stock,
        'status'          => $status,
        'expiration_date' => $expirationDate,
        'bestseller'      => $bestseller
    ]);

    // Retrieve auto-increment ID generated by MySQL
    $newId = (int)$pdo->lastInsertId();

    sendResponse([
        'success' => true,
        'message' => "Product '{$name}' created successfully!",
        'product' => [
            'id'              => $newId,
            'name'            => $name,
            'description'     => $description,
            'category'        => $category,
            'price'           => $price,
            'image'           => $image,
            'stock'           => $stock,
            'status'          => $status,
            'expiration_date' => $expirationDate,
            'bestseller'      => (bool)$bestseller
        ]
    ], 201);

} catch (PDOException $e) {
    sendResponse(['success' => false, 'message' => 'Database error: ' . $e->getMessage()], 500);
}
?>
